-- 프로필 사진을 우리가 보관한다.
--
-- V1 의 users.avatar_url 은 **소셜 제공자가 준 남의 주소**다(구글·네이버). 그 값은 우리가 지울 수도
-- 바꿀 수도 없고, 제공자가 주소를 바꾸면 깨진다. 사용자가 직접 올린 사진은 우리 버킷에 있으므로
-- 주소가 아니라 **객체 키**를 들고 있어야 한다. 두 값을 한 칸에 섞으면 "이 문자열이 남의 URL 인가
-- 우리 키인가" 를 읽는 쪽마다 판별해야 한다.
--
-- 그래서 칸을 따로 둔다. 둘 다 있으면 올린 사진이 이긴다(UserResponse 가 그렇게 고른다).
-- 사진을 지우면 이 칸만 비고 소셜 사진으로 되돌아간다.
--
-- 키는 `profile/<사용자 id>/<uuid>.<확장자>` 다. 사용자별 폴더로 나눠 두면 콘솔에서 찾기 쉽고,
-- 계정을 지울 때 그 마디만 비우면 된다.
--
-- 이 객체는 **로그인 없이** 내려받을 수 있게 연다 — 프로필 사진은 화면 곳곳의 <img> 태그가 그리는데
-- 그 태그에는 Authorization 헤더를 실을 수 없다. 자물쇠는 파일 이름 쪽 uuid 다. 폴더 이름(사용자 id)은
-- 계정 화면이 이미 사용자에게 보여 주는 값이라 감추는 값이 아니고, 그걸 안다고 파일 이름을 맞힐 수는 없다.
-- 사진을 바꾸면 새 uuid 를 발급하고 옛 객체를 지운다 — 옛 주소가 살아남지 않는다.

ALTER TABLE shared.users ADD COLUMN avatar_object_key varchar(200);

COMMENT ON COLUMN shared.users.avatar_url IS '소셜 제공자가 준 프로필 사진 주소. 우리가 관리하지 않는다.';
COMMENT ON COLUMN shared.users.avatar_object_key IS '사용자가 올린 프로필 사진의 오브젝트 스토리지 키(profile/<사용자 id>/<uuid>.<ext>). 로그인 없이 열리는 주소라 파일 이름을 추측할 수 없어야 한다.';
