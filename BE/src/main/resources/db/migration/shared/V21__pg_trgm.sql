-- 부분 일치 검색을 위한 pg_trgm 확장.
--
-- **여기에는 데이터가 없다.** V15(pgvector)와 같은 이유로 확장만 설치한다. 확장은 데이터베이스 단위이고 스키마는
-- 설치 위치일 뿐이라, 회사마다 따로 만들 것이 아니다.
--
-- 왜 필요한가: AI 문서 검색의 전문 검색 색인이 `to_tsvector('simple', ...)` 이다. 형태소 분석이 없어서 조사가 붙은
-- 채로 토큰이 된다 — "단가는" 과 "단가" 가 다른 낱말이다. 세 글자 단위(trigram) 색인은 낱말 경계를 보지 않으므로
-- 조사가 붙어도, 품번 일부만 알아도 걸린다.
--
-- `public` 에 두는 이유도 V15 와 같다. 테넌트 검색 경로에 `public` 을 넣지 않으므로 부르는 쪽이
-- `public.gin_trgm_ops` · `OPERATOR(public.%>)` 처럼 스키마를 붙여 쓴다.
--
-- 이미지에 확장이 없으면 여기서 멈춘다. 조용히 넘어가면 색인을 만들 때 터진다.

CREATE EXTENSION IF NOT EXISTS pg_trgm SCHEMA public;
